"""Bundle the pbp2track package into one Kaggle script.

Kaggle script kernels run a single file. This writes <out> that recreates the package
under /tmp at start-up, then runs the given script.

usage: python tools/bundle_kernel.py kaggle/heldout_eval.py out/heldout_eval_bundled.py
"""
import base64
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PKG = ROOT / "src" / "pbp2track"


def main(script: str, out: str):
    main_src = pathlib.Path(script).read_text(encoding="utf-8")
    files = {p.name: base64.b64encode(p.read_bytes()).decode() for p in sorted(PKG.glob("*.py"))}
    header = [
        "# Generated by tools/bundle_kernel.py from the pbp2track package. Edit the sources, then re-bundle.",
        "import base64 as _b64, os as _os, sys as _sys",
        "_PKG = '/tmp/pkg/pbp2track'",
        "_os.makedirs(_PKG, exist_ok=True)",
        f"_FILES = {files!r}",
        "for _n, _s in _FILES.items():",
        "    open(_os.path.join(_PKG, _n), 'wb').write(_b64.b64decode(_s))",
        "_sys.path.insert(0, '/tmp/pkg')",
        "",
    ]
    path = pathlib.Path(out)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(header) + main_src, encoding="utf-8")
    print(f"wrote {path} ({path.stat().st_size // 1024} KB, {len(files)} modules)")


if __name__ == "__main__":
    main(*sys.argv[1:3])
